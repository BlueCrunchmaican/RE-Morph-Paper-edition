package dev.morphreborn.client.dev;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.google.gson.JsonElement;
import com.google.gson.JsonParser;
import com.mojang.serialization.JsonOps;
import java.io.IOException;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Stream;
import net.minecraft.client.renderer.item.ClientItem;
import net.minecraft.client.renderer.item.ItemModels;
import net.minecraft.client.renderer.item.properties.conditional.ConditionalItemModelProperties;
import net.minecraft.client.renderer.item.properties.numeric.RangeSelectItemModelProperties;
import net.minecraft.client.renderer.item.properties.select.SelectItemModelProperties;
import net.minecraft.client.resources.model.cuboid.CuboidModel;
import org.junit.jupiter.api.Test;

/**
 * The resource pack's arm item definitions and models, read by the game's own parsers (no game is started: the codecs
 * and the model deserializer are plain classes), so a typo in a property name, a threshold list, a transformation or a
 * rotation is found here and not as a missing-model cube in a player's hand. The pack is generated by
 * tools/gen_arm_pack.py; this checks what it wrote.
 */
class ArmPackParseTest {
	private static boolean booted;
	private static final Path PACK = Path.of("..", "resourcepack", "assets", "morphreborn");

	@Test
	void everyArmItemDefinitionParsesAndNeverPlaysTheEquipBob() throws IOException {
		// what the game's own bootstrap registers: the model types and the three families of properties
		if (!booted) {
			booted = true;
			net.minecraft.SharedConstants.tryDetectVersion();
			net.minecraft.server.Bootstrap.bootStrap(); // the properties name registries (data components, game events)
			ItemModels.bootstrap();
			SelectItemModelProperties.bootstrap();
			ConditionalItemModelProperties.bootstrap();
			RangeSelectItemModelProperties.bootstrap();
		}
		Path items = PACK.resolve("items").resolve("arm");
		if (!Files.isDirectory(items)) return; // no pack beside the client
		int parsed = 0;
		try (Stream<Path> files = Files.list(items)) {
			for (Path file : files.filter(p -> p.toString().endsWith(".json")).toList()) {
				JsonElement json = JsonParser.parseString(Files.readString(file, StandardCharsets.UTF_8));
				var result = ClientItem.CODEC.parse(JsonOps.INSTANCE, json);
				assertTrue(result.result().isPresent(), file + " doesn't parse: " + result.error().map(e -> e.message()).orElse("?"));
				assertFalse(result.result().get().properties().handAnimationOnSwap(), file + " plays the equip bob");
				parsed++;
			}
		}
		assertTrue(parsed >= 2, "the arm item definitions are there: " + parsed);
	}

	@Test
	void everyArmModelParses() throws IOException {
		Path models = PACK.resolve("models").resolve("item").resolve("arm");
		if (!Files.isDirectory(models)) return;
		int parsed = 0;
		try (Stream<Path> files = Files.walk(models)) {
			for (Path file : files.filter(p -> p.toString().endsWith(".json")).toList()) {
				try (Reader in = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
					CuboidModel model = CuboidModel.fromStream(in);
					assertTrue(model != null, file.toString());
				} catch (RuntimeException e) {
					throw new AssertionError(file + " doesn't parse: " + e.getMessage(), e);
				}
				parsed++;
			}
		}
		assertTrue(parsed > 100, "the arm models are there: " + parsed);
		assertEquals(List.of(), List.of());
	}
}
