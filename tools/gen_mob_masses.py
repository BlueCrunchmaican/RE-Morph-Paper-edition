"""Write docs/MOB-MASSES.md: every morphable mob's mass, what Survival Mode needs to absorb it, and what it gives.

Mass is iChun's formula, width x width x height x 1000 kg, from the mob's size in Minecraft 26.3. The sizes are read
from the decompiled EntityTypes.java (reference/mc-26.3-src, which is never committed). The mob list is the one in
docs/ABILITIES.md. The levels and rates are the defaults in survival.yml.

Usage: py -3 tools/gen_mob_masses.py [EntityTypes.java] [--json out.json]
"""
import json
import math
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ENTITY_TYPES = os.path.join(ROOT, "reference", "mc-26.3-src", "net", "minecraft", "world", "entity", "EntityTypes.java")

# survival.yml defaults
BIOMASS_VALUE = 0.3
EFFICIENCY_START, EFFICIENCY_MAX = 10, 55
COST_PER_KG, COST_MIN = 0.01, 1
MASS_LEVELS = [(1, 1200), (2, 3000), (3, 10000), (4, 160000), (5, math.inf)]
LEVEL_NAMES = {1: "from the start (up to 1,200 kg)", 2: "Absorbable Mass 2 (up to 3,000 kg)", 3: "Absorbable Mass 3 (up to 10,000 kg)",
               4: "Absorbable Mass 4 (up to 160,000 kg)", 5: "Absorbable Mass 5 (no limit)"}
# Cube mobs grow with their Size: the type's size times 1, 2 or 4 (slimes, magma cubes) or 1 or 2 (sulfur cubes).
CUBE_SIZES = {"slime": [1, 2, 4], "magma_cube": [1, 2, 4], "sulfur_cube": [1, 2]}
CUBE_NAMES = {1: "small", 2: "medium", 4: "big"}


def sizes(path):
    text = open(path, encoding="utf-8").read()
    out = {}
    for m in re.finditer(r"public static final EntityType<[^>]+> (\w+) = register\((.*?)\n\t\);", text, re.S):
        s = re.search(r"\.sized\(([\d.]+)F, ([\d.]+)F\)", m.group(2))
        if s:
            out[m.group(1).lower()] = (float(s.group(1)), float(s.group(2)))
    return out


def mobs():
    names = []
    for line in open(os.path.join(ROOT, "docs", "ABILITIES.md"), encoding="utf-8"):
        m = re.match(r"\| ([a-z][a-z ]*?) \|", line)
        if m and m.group(1) != "mob":
            names.append(m.group(1).replace(" ", "_"))
    return names


def level_for(mass):
    return next(level for level, limit in MASS_LEVELS if mass <= limit + 1e-9)


def rows(size_table):
    out = []
    for mob in mobs():
        if mob not in size_table:
            print("no size for", mob, file=sys.stderr)
            continue
        w, h = size_table[mob]
        for scale in CUBE_SIZES.get(mob, [1]):
            name = mob.replace("_", " ") + (f" ({CUBE_NAMES[scale]})" if mob in CUBE_SIZES else "")
            mass = (w * scale) ** 2 * (h * scale) * 1000
            out.append({"mob": name, "width": round(w * scale, 4), "height": round(h * scale, 4), "mass": mass, "level": level_for(mass),
                        "biomass_start": mass * BIOMASS_VALUE * EFFICIENCY_START / 100, "biomass_max": mass * BIOMASS_VALUE * EFFICIENCY_MAX / 100,
                        "morph_cost": max(COST_MIN, math.ceil(mass * COST_PER_KG - 1e-9))})
    out.sort(key=lambda r: r["mass"])
    return out


def n(x):
    return f"{x:,.0f}" if x >= 10 else f"{x:,.1f}".rstrip("0").rstrip(".")


def markdown(table):
    lines = ["# Mob masses (Survival Mode)", "",
             "Generated by `tools/gen_mob_masses.py` from Minecraft 26.3's mob sizes and the default `survival.yml`.", "",
             "A creature's mass is iChun's formula: width × width × height × 1000 kg. It decides three things in Survival Mode:", "",
             "- **Whether you can absorb it:** your Absorbable Mass upgrade must reach its mass (the sections below).",
             f"- **The biomass a kill gives:** mass × {BIOMASS_VALUE} × your Biomass Efficiency ({EFFICIENCY_START}% at the start, "
             f"{EFFICIENCY_MAX}% fully upgraded), never more than your storage has room for.",
             f"- **What morphing into it costs:** mass × {COST_PER_KG}, rounded up, at least {COST_MIN}.", "",
             "Babies are about an eighth of the adult's mass (half the size each way), so they give and cost less. A player is "
             "648 kg. Servers can change any mob's mass in `survival.yml` (`biomass.multipliers`, `biomass.masses`).", ""]
    for level in range(1, 6):
        group = [r for r in table if r["level"] == level]
        if not group:
            continue
        lines += [f"## {LEVEL_NAMES[level][0].upper() + LEVEL_NAMES[level][1:]}", "",
                  "| Mob | Size (blocks) | Mass | Biomass per kill (start / max) | Morph cost |", "|---|---|---|---|---|"]
        for r in group:
            lines.append(f"| {r['mob']} | {r['width']:g} × {r['height']:g} | {n(r['mass'])} kg | {n(r['biomass_start'])} / {n(r['biomass_max'])} | {r['morph_cost']:,} |")
        lines.append("")
    return "\n".join(lines)


def main():
    args = sys.argv[1:]
    json_out = None
    if "--json" in args:
        i = args.index("--json")
        json_out = args[i + 1]
        del args[i:i + 2]
    table = rows(sizes(args[0] if args else ENTITY_TYPES))
    out = os.path.join(ROOT, "docs", "MOB-MASSES.md")
    open(out, "w", encoding="utf-8", newline="\n").write(markdown(table))
    print(len(table), "rows ->", out)
    if json_out:
        json.dump(table, open(json_out, "w", encoding="utf-8"), indent=1)
        print("json ->", json_out)


if __name__ == "__main__":
    main()
